import type { Feedback, Source } from './shared';

export type ExportFormat = 'markdown' | 'json';

export interface ExportOptions {
  language: 'nl' | 'en';
  format: ExportFormat;
  fullText: boolean;
  notes: boolean;
  maskNames: boolean;
}

export const defaultExportOptions: ExportOptions = { language: 'nl', format: 'markdown', fullText: true, notes: true, maskNames: false };

export interface AiExport {
  content: string;
  filename: string;
  mime: string;
  sessions: number;
  feedback: number;
  estimatedTokens: number;
}

function count(values: string[]) {
  const map = new Map<string, number>();
  for (const value of values) if (value) map.set(value, (map.get(value) ?? 0) + 1);
  return [...map].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

function masker(names: string[], language: 'nl' | 'en', enabled: boolean) {
  const unique = [...new Set(names)].filter(Boolean).sort((a, b) => b.length - a.length);
  if (!enabled || !unique.length) return (text: string) => text;
  const aliases = new Map(unique.map((name, index) => [name.toLowerCase(), `${language === 'nl' ? 'Klant' : 'Customer'} ${index + 1}`]));
  const pattern = new RegExp(unique.map(name => name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'gi');
  return (text: string) => text.replace(pattern, match => aliases.get(match.toLowerCase()) ?? match);
}

export function buildAiExport(options: ExportOptions, feedback: Feedback[], allSources: Source[], now = new Date()): AiExport {
  const nl = options.language === 'nl';
  const ids = new Set(feedback.map(item => item.sourceId));
  const sources = allSources.filter(source => ids.has(source.id));
  const mask = masker([...feedback.map(item => item.customer), ...sources.map(source => source.customer)], options.language, options.maskNames);
  const stamp = now.toISOString().slice(0, 10);
  const dates = sources.map(source => source.date).filter(Boolean).sort();
  const topics = count(feedback.flatMap(item => item.topics));
  const sentiment = count(feedback.map(item => item.sentiment));
  const bySource = (id: string) => feedback.filter(item => item.sourceId === id);

  let content: string;
  if (options.format === 'json') {
    content = JSON.stringify({
      generatedBy: 'Feedbacker',
      generatedAt: now.toISOString(),
      instructions: nl
        ? 'Beantwoord vragen alleen op basis van deze feedback. Verwijs naar feedback-ID\'s en sessies. Benoem onzekerheid en verzin geen bewijs.'
        : 'Answer questions using only this feedback. Cite feedback IDs and sessions. State uncertainty and never invent evidence.',
      scope: {
        sessions: sources.length, feedback: feedback.length,
        customers: new Set(feedback.map(item => item.customer)).size,
        period: dates.length ? { from: dates[0], to: dates[dates.length - 1] } : null,
        knownCustomerNamesReplaced: options.maskNames,
      },
      topics: Object.fromEntries(topics), sentiment: Object.fromEntries(sentiment),
      sessions: sources.map(source => ({
        id: source.id, file: mask(source.filename), customer: mask(source.customer), product: source.product, date: source.date || null,
        tags: source.tags ?? [], summary: mask(source.summary),
        ...(options.fullText ? { fullText: mask(source.text) } : {}),
        feedback: bySource(source.id).map(item => ({
          id: item.id, title: mask(item.title), topics: item.topics, sentiment: item.sentiment, priority: item.priority, status: item.status,
          evidence: mask(item.evidence || item.excerpt), ...(options.notes && item.notes ? { teamNotes: mask(item.notes) } : {}),
        })),
      })),
    }, null, 2);
  } else {
    const lines: string[] = [];
    const push = (...rows: string[]) => lines.push(...rows);
    push(
      `# ${nl ? 'Klantfeedback — export voor AI' : 'Customer feedback — AI export'}`, '',
      `> ${nl ? 'Gemaakt met Feedbacker op' : 'Generated by Feedbacker on'} ${stamp}. ${nl ? 'Bevat klantinformatie: deel alleen volgens het beleid van je organisatie.' : 'Contains customer information: share only according to your organization\'s policy.'}`, '',
      `## ${nl ? 'Instructies voor de AI-assistent' : 'Instructions for the AI assistant'}`, '',
      ...(nl ? [
        '- Beantwoord vragen alleen op basis van dit document.',
        '- Verwijs bij elke bewering naar het feedback-ID (bijv. `[fb:…]`) en de klant/sessie.',
        '- Maak onderscheid tussen wat klanten letterlijk zeggen en jouw interpretatie.',
        '- Zeg het eerlijk als het antwoord niet in de feedback staat; verzin geen bewijs.',
        '- Teamnotities zijn interne opmerkingen, geen klantuitspraken.',
      ] : [
        '- Answer questions using only this document.',
        '- Cite the feedback ID (e.g. `[fb:…]`) and customer/session for every claim.',
        '- Separate what customers literally said from your interpretation.',
        '- Say so when the answer is not in the feedback; never invent evidence.',
        '- Team notes are internal remarks, not customer statements.',
      ]), '',
      `## ${nl ? 'Overzicht' : 'Overview'}`, '',
      `- ${nl ? 'Sessies' : 'Sessions'}: ${sources.length}`,
      `- ${nl ? 'Feedbackpunten' : 'Feedback items'}: ${feedback.length}`,
      `- ${nl ? 'Klanten' : 'Customers'}: ${new Set(feedback.map(item => item.customer)).size}`,
      `- ${nl ? 'Periode' : 'Period'}: ${dates.length ? `${dates[0]} – ${dates[dates.length - 1]}` : nl ? 'onbekend' : 'unknown'}`,
      `- ${nl ? 'Sentiment' : 'Sentiment'}: ${sentiment.map(([name, n]) => `${name} ${n}`).join(', ') || '—'}`,
      `- ${nl ? 'Onderwerpen' : 'Topics'}: ${topics.slice(0, 15).map(([name, n]) => `${name} (${n})`).join(', ') || '—'}`,
      ...(options.maskNames ? [`- ${nl ? 'Bekende klantnamen zijn vervangen door Klant 1, Klant 2, … (geen volledige anonimisering).' : 'Known customer names are replaced by Customer 1, Customer 2, … (not full anonymization).'}`] : []),
      '',
    );
    sources.forEach((source, index) => {
      push(
        '---', '',
        `## ${nl ? 'Sessie' : 'Session'} ${index + 1}: ${mask(source.customer)} — ${source.product}`, '',
        `- ${nl ? 'Datum' : 'Date'}: ${source.date || (nl ? 'onbekend' : 'unknown')}`,
        `- ${nl ? 'Bestand' : 'File'}: ${mask(source.filename)} (\`${source.id}\`)`,
        ...(source.tags?.length ? [`- Tags: ${source.tags.join(', ')}`] : []),
        '',
      );
      if (source.summary) push(`**${nl ? 'Samenvatting' : 'Summary'}:** ${mask(source.summary)}`, '');
      push(`### ${nl ? 'Feedbackpunten' : 'Feedback items'}`, '');
      for (const item of bySource(source.id)) {
        push(
          `#### [fb:${item.id}] ${mask(item.title)}`,
          `${nl ? 'Onderwerpen' : 'Topics'}: ${item.topics.join(', ') || '—'} · Sentiment: ${item.sentiment} · ${nl ? 'Prioriteit' : 'Priority'}: ${item.priority} · Status: ${item.status}`, '',
          ...mask(item.evidence || item.excerpt).split('\n').map(row => `> ${row}`), '',
          ...(options.notes && item.notes ? [`*${nl ? 'Teamnotitie' : 'Team note'}:* ${mask(item.notes)}`, ''] : []),
        );
      }
      if (options.fullText && source.text.trim()) {
        push(`### ${nl ? 'Volledige tekst van de sessie' : 'Full session text'}`, '', '```text', mask(source.text.trim()).replace(/```/g, "'''"), '```', '');
      }
    });
    content = lines.join('\n');
  }

  return {
    content,
    filename: `feedbacker-ai-export-${stamp}.${options.format === 'json' ? 'json' : 'md'}`,
    mime: options.format === 'json' ? 'application/json;charset=utf-8' : 'text/markdown;charset=utf-8',
    sessions: sources.length,
    feedback: feedback.length,
    estimatedTokens: Math.ceil(content.length / 4),
  };
}
